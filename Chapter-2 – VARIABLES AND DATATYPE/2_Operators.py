#Comparison Operators
c = 5<4 # Check if 5 is less than 4
print(c)
d = 5>5 # Check if 5 is greater than 5
print(d)
e = 5==5 # Check if 5 is equal to 5
print(e)
f = 5!=5 # Check if 5 is not equal to 5
print(f)

