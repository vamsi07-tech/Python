"""
=========================================================
        PYTHON LIST METHODS
=========================================================
"""

import copy

# =========================================================
# LIST CREATION
# =========================================================

numbers = [10, 20, 30, 40, 50]

print("Original List :", numbers)

print("-" * 60)

# =========================================================
# INDEXING
# =========================================================

print("First Element        :", numbers[0])
print("Last Element         :", numbers[-1])

print("-" * 60)

# =========================================================
# SLICING
# =========================================================

print("First 3 Elements     :", numbers[:3])
print("Last 3 Elements      :", numbers[-3:])
print("Reverse List         :", numbers[::-1])
print("Alternate Elements   :", numbers[::2])

print("-" * 60)

# =========================================================
# APPEND
# =========================================================

temp = numbers.copy()

temp.append(60)

print("append()             :", temp)

print("-" * 60)

# =========================================================
# EXTEND
# =========================================================

temp = numbers.copy()

temp.extend([60, 70, 80])

print("extend()             :", temp)

print("-" * 60)

# =========================================================
# INSERT
# =========================================================

temp = numbers.copy()

temp.insert(2, 25)

print("insert()             :", temp)

print("-" * 60)

# =========================================================
# REMOVE
# =========================================================

temp = numbers.copy()

temp.remove(30)

print("remove()             :", temp)

print("-" * 60)

# =========================================================
# POP
# =========================================================

temp = numbers.copy()

removed = temp.pop()

print("pop()                :", temp)
print("Removed Element      :", removed)

removed = temp.pop(1)

print("pop(index)           :", temp)
print("Removed Element      :", removed)

print("-" * 60)

# =========================================================
# CLEAR
# =========================================================

temp = numbers.copy()

temp.clear()

print("clear()              :", temp)

print("-" * 60)

# =========================================================
# COPY
# =========================================================

copy_list = numbers.copy()

print("copy()               :", copy_list)

print("-" * 60)

# =========================================================
# COUNT
# =========================================================

sample = [1,2,2,3,4,2]

print("count()              :", sample.count(2))

print("-" * 60)

# =========================================================
# INDEX
# =========================================================

print("index()              :", sample.index(3))

print("-" * 60)

# =========================================================
# SORT
# =========================================================

data = [7,2,9,1,5]

temp = data.copy()

temp.sort()

print("sort() Ascending     :", temp)

temp.sort(reverse=True)

print("sort() Descending    :", temp)

print("-" * 60)

# =========================================================
# REVERSE
# =========================================================

temp = data.copy()

temp.reverse()

print("reverse()            :", temp)

print("-" * 60)

# =========================================================
# MEMBERSHIP
# =========================================================

print("20 in numbers        :", 20 in numbers)
print("100 in numbers       :", 100 in numbers)

print("-" * 60)

# =========================================================
# CONCATENATION
# =========================================================

list1 = [1,2]
list2 = [3,4]

print("Concatenation (+)    :", list1 + list2)

print("-" * 60)

# =========================================================
# REPETITION
# =========================================================

print("Repetition (*)       :", [1,2] * 3)

print("-" * 60)

# =========================================================
# BUILT-IN FUNCTIONS
# =========================================================

print("len()                :", len(numbers))
print("max()                :", max(numbers))
print("min()                :", min(numbers))
print("sum()                :", sum(numbers))

print("-" * 60)

# =========================================================
# SORTED FUNCTION
# =========================================================

print("sorted()             :", sorted(data))

print("Original List        :", data)

print("-" * 60)

# =========================================================
# REVERSED FUNCTION
# =========================================================

print("reversed()           :", list(reversed(data)))

print("-" * 60)

# =========================================================
# ENUMERATE
# =========================================================

print("enumerate()")

for index, value in enumerate(numbers):
    print(index, value)

print("-" * 60)

# =========================================================
# ZIP
# =========================================================

names = ["A","B","C"]
marks = [90,80,70]

print("zip()                :", list(zip(names, marks)))

print("-" * 60)

# =========================================================
# LIST COMPREHENSION
# =========================================================

square = [x*x for x in range(6)]

print("List Comprehension   :", square)

even = [x for x in range(20) if x % 2 == 0]

print("Even Numbers         :", even)

print("-" * 60)

# =========================================================
# SHALLOW COPY
# =========================================================

nested = [[1,2],[3,4]]

shallow = nested.copy()

shallow[0][0] = 99

print("Original             :", nested)
print("Shallow Copy         :", shallow)

print("-" * 60)

# =========================================================
# DEEP COPY
# =========================================================

nested = [[1,2],[3,4]]

deep = copy.deepcopy(nested)

deep[0][0] = 100

print("Original             :", nested)
print("Deep Copy            :", deep)

print("-" * 60)

# =========================================================
# LIST TO STRING
# =========================================================

letters = ['P','Y','T','H','O','N']

print("join()               :", "".join(letters))

print("-" * 60)

# =========================================================
# STRING TO LIST
# =========================================================

text = "Python is Easy"

print("split()              :", text.split())

print("-" * 60)

# =========================================================
# NESTED LIST
# =========================================================

matrix = [
    [1,2,3],
    [4,5,6],
    [7,8,9]
]

print("Nested List          :", matrix)
print("Element              :", matrix[1][2])

print("-" * 60)

# =========================================================
# UNPACKING
# =========================================================

a,b,c,d,e = numbers

print("Unpacking            :", a,b,c,d,e)

print("-" * 60)

# =========================================================
# IDENTITY
# =========================================================

l1 = [1,2,3]

l2 = l1

l3 = l1.copy()

print("l1 is l2             :", l1 is l2)
print("l1 is l3             :", l1 is l3)

print("-" * 60)

# =========================================================
# COMMON INTERVIEW OPERATIONS
# =========================================================

print("Largest              :", max(numbers))
print("Smallest             :", min(numbers))
print("Second Largest       :", sorted(numbers)[-2])

print("-" * 60)

print("************** END OF LIST REVISION **************")