a = 'Vamsi'
print(a[0:3]) # Start from index 0 all the way till 3 (3 not included)
print(a[1:3]) # Start from index 1 all the way till 3 (3 not included)
print(a[1]) # Prints character at index 1

print("Neagtive Slicing")
print(a[-4:-1]) # Start from index -4 all the way till -1 (-1 not included)])
print(a[1:4]) # Start from index 1 all the way till 4 (4 not included)

print("String Slicing with skip value")
print(a[0:4:2]) # Start from index 0 all the way till 5 (5 not included) with skip value of 1
